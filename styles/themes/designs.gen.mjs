// Generates styles/designs.css and lib/designs.gen.js from the design styles in this folder, so a visitor can switch
// styles in the browser (components/theme/designs.js) instead of only by editing styles/main.css.
// Run after adding or editing a style:  node styles/themes/designs.gen.mjs
//
// Each style is wrapped in a donut @scope: from an element with its name in data-design (<html>, or a section the
// theme controls gave a style of its own) down to, but not into, an element with another one. So a section's style
// replaces the page's inside it instead of mixing with it. Selectors inside an @scope are scoped without gaining
// weight, so specificity and order stay as they were in the file; only the root selector is rewritten:
//   :where(:root) { … }           ->  :where(:scope) { … }
//   :where(:root, [data-theme=x]) ->  :where(:scope, [data-theme=x])
//   :root …                       ->  :scope …
// @imports (the self-hosted fonts) are hoisted to the top, once each; a font file only downloads when a style uses it.
// @keyframes move out of the scope (they can't be scoped; their names are unique per style).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import postcss from 'postcss';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const files = fs.readdirSync(here).filter(f => f.endsWith('.css')).sort();

// Splits a selector list at top-level commas.
const splitTop = (s) => {
  const out = []; let depth = 0, cur = '';
  for (const ch of s) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  return [ ...out, cur.trim() ];
};

const scopeSelector = (sel) => {
  const m = sel.match(/^:where\((.*?)\)(.*)$/s);
  if (m) {
    const args = splitTop(m[1]);
    if (args.includes(':root')) return `:where(${args.map(a => a === ':root' ? ':scope' : a).join(', ')})${m[2]}`;
  }
  if (sel.startsWith(':root')) return `:scope${sel.slice(5)}`;
  return sel;
};

// The style's name and one-line description from its header comment ("THEME: Terminal. Optional. A command line: …").
const describe = (css, file) => {
  const text = (css.match(/\/\*([\s\S]*?)\*\//g) ?? []).map(c => c.replace(/^\/\*|\*\/$/g, '').replace(/^\s*\* ?/gm, '')).join('\n');
  const m = text.match(/THEME:\s*([^.]+)\.\s*Optional\.\s*([\s\S]*?)(?:\n\s*\n|\nTry it|$)/);
  return {
    name: path.basename(file, '.css'),
    title: m?.[1].trim() ?? path.basename(file, '.css'),
    description: (m?.[2] ?? '').replace(/\s+/g, ' ').trim(),
  };
};

// The variables defaults.css works out from others on :root (--font-heading from --font-body, the text and space
// steps…). Worked out once on <html>, they would keep the page's values inside a section with a style of its own, so
// each style's scope starts by working them out again; its own values follow and win. Colors are left out: a themed
// section gets its shades from the theme controls (lib/section-theme.js).
const defaults = postcss.parse(fs.readFileSync(path.join(root, 'styles/tokens/defaults.css'), 'utf8'));
const derived = [];
defaults.walkRules((rule) => {
  if (rule.selector.trim() !== ':where(:root)') return;
  rule.walkDecls((d) => { if (/var\(/.test(d.value) && !/lighter|darker|gradient/.test(d.prop)) derived.push(`${d.prop}: ${d.value};`); });
});
const rederive = `:where(:scope) { ${derived.join(' ')} }`;

const imports = new Set();
const blocks = [];
const list = [];
const keyframes = new Map();

for (const file of files) {
  const css = fs.readFileSync(path.join(here, file), 'utf8');
  const info = describe(css, file);
  list.push(info);
  const tree = postcss.parse(css);
  tree.walkAtRules('import', (rule) => { imports.add(`@import ${rule.params};`); rule.remove(); });
  const frames = [];
  tree.walkAtRules(/keyframes$/, (rule) => {
    if (keyframes.has(rule.params)) console.warn(`@keyframes ${rule.params} in ${file} and ${keyframes.get(rule.params)}`);
    keyframes.set(rule.params, file);
    frames.push(rule.toString());
    rule.remove();
  });
  tree.walkRules((rule) => { rule.selectors = rule.selectors.map(scopeSelector); });
  tree.walkComments(c => c.remove());
  const body = tree.toString().trim().replace(/^/gm, '  ');
  blocks.push(`/* ${info.title} (styles/themes/${file}) */\n`
    + `@scope ([data-design="${info.name}"]) to ([data-design]:not([data-design="${info.name}"])) {\n  ${rederive}\n${body}\n}`
    + (frames.length ? `\n${frames.join('\n')}` : ''));
}

const head = `/* GENERATED by styles/themes/designs.gen.mjs from styles/themes/*.css: don't edit, edit the style and run it again.
   Every design style, each under [data-design="<name>"] (set on <html> by the theme controls; lib/design.js has the
   default). */\n`;
fs.writeFileSync(path.join(root, 'styles/designs.css'), `${head}${[ ...imports ].join('\n')}\n\n${blocks.join('\n\n')}\n`);
fs.writeFileSync(path.join(root, 'lib/designs.gen.js'),
  `// GENERATED by styles/themes/designs.gen.mjs: the design styles in styles/themes, with their header descriptions.\n`
  + `export const DESIGNS = ${JSON.stringify(list, null, 2)};\n`);
console.log(`${list.length} styles, ${imports.size} font imports -> styles/designs.css, lib/designs.gen.js`);
